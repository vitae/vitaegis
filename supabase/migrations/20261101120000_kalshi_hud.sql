-- The Rust Kalshi bot (kalshi-bot.service on the Lightsail VPS) writes market_windows and
-- trade_executions with the service role key. This migration makes them readable by the
-- public HUD at vitaegis.com/kalshi and streams their changes over Realtime. It creates the
-- tables only when the bot has not already; the column shapes match the bot's.
-- Contract: docs/kalshi-hud.md.

create table if not exists market_windows (
  id integer generated by default as identity primary key,
  ticker text not null,
  strike double precision not null,
  close_time timestamptz not null,
  bets_placed integer default 0,
  status text default 'open',
  created_at timestamptz default now()
);

create table if not exists trade_executions (
  id integer generated by default as identity primary key,
  window_ticker text not null,
  action text not null,               -- YES | NO
  price double precision not null,    -- contract price in dollars (0.35)
  size double precision not null,     -- contracts
  blended_prob double precision not null,  -- GBM 40% + XGBoost 60%, 0–1
  executed_at timestamptz default now()
);

create index if not exists market_windows_close_idx on market_windows (close_time desc);
create index if not exists market_windows_ticker_idx on market_windows (ticker);
create index if not exists trade_executions_executed_idx on trade_executions (executed_at desc);
create index if not exists trade_executions_window_idx on trade_executions (window_ticker, executed_at desc);

-- Public read, service-role write. The HUD is a public page.
alter table market_windows enable row level security;
alter table trade_executions enable row level security;

-- The bot's setup created an allow-everything policy for every role, which let the
-- website's anon key write. The bot writes with the service-role key, which bypasses RLS.
drop policy if exists "Allow server insert/select" on market_windows;
drop policy if exists "Allow server insert/select" on trade_executions;

drop policy if exists "public read market_windows" on market_windows;
create policy "public read market_windows" on market_windows
  for select to anon, authenticated using (true);
drop policy if exists "public read trade_executions" on trade_executions;
create policy "public read trade_executions" on trade_executions
  for select to anon, authenticated using (true);

grant select on market_windows, trade_executions to anon, authenticated;

-- Realtime: the HUD listens for inserts and updates on both.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'market_windows'
  ) then
    alter publication supabase_realtime add table market_windows;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and tablename = 'trade_executions'
  ) then
    alter publication supabase_realtime add table trade_executions;
  end if;
end $$;

-- Updates carry the full row for Realtime UPDATE payloads.
alter table market_windows replica identity full;
alter table trade_executions replica identity full;
